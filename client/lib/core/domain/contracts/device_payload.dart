/// Абстрактный контракт для данных, которые могут быть отправлены на устройство.
/// Позволяет слою связи не знать о деталях конкретных доменных сущностей.
abstract interface class IDevicePayload {
  /// Преобразует сущность в формат, понятный прошивке устройства.
  Map<String, dynamic> toDeviceJson();
}
